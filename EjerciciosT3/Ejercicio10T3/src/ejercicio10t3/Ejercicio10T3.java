public class Ejercicio10T3 {

    /**
     * • Ejercicio 10.- Escribe un programa en JAVA que, utilizando
        bucles, muestre por pantalla el mensaje "Hola" cinco veces.
        • Pista: Como sabes cuantas veces se ejecuta el bucle, deberás
        utilizar un bucle for.
     */
    public static void main(String[] args) {
        // Declaro las variables
        int i;
        //Itero cinco veces
        for(i=0;i<5;i++)
            System.out.println("Hola");
    }

}
